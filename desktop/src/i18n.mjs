export function normalizeDesktopLanguage(value) {
  const language = String(value || '').trim().toLowerCase()
  if (language === 'en' || language.startsWith('en-')) return 'en'
  if (language === 'zh' || language.startsWith('zh-')) return 'zh-CN'
  return 'auto'
}

export function effectiveDesktopLanguage(value, systemLanguage = '') {
  const configured = normalizeDesktopLanguage(value)
  if (configured !== 'auto') return configured
  return /^zh(?:-|$)/i.test(String(systemLanguage || '')) ? 'zh-CN' : 'en'
}

export function desktopTranslator(language, systemLanguage = '') {
  const english = effectiveDesktopLanguage(language, systemLanguage) === 'en'
  return (text, params) => {
    const source = String(text ?? '')
    const translated = english ? (ENGLISH[source] ?? source) : source
    if (!params) return translated
    return translated.replace(/\{(\w+)\}/g, (match, key) => (
      key in params ? String(params[key]) : match
    ))
  }
}

export function localizeDesktopError(value, translate) {
  const text = String(value || '')
  const replacements = [
    [/^路径不能为空$/, 'Node.js path cannot be empty'],
    [/^目录不存在：(.+)$/, 'Directory does not exist: $1'],
    [/^无法打开日志目录：(.+)$/, 'Could not open logs folder: $1'],
    [/^不支持的后台(?: Agent)?：(.+)$/, 'Unsupported backend Agent: $1'],
    [/^请先填写 DashScope API Key$/, 'Enter a DashScope API Key first'],
    [/^请先填写 Speech-to-Speech 服务地址$/, 'Enter the Speech-to-Speech service URL first'],
    [/^无法连接 Gateway：(.+)$/, 'Could not connect to Gateway: $1'],
    [/^这个显示快捷键已被其他应用占用，请选择另一个$/, 'This shortcut is used by another app. Choose another one.'],
    [/^请填写外部后台服务地址$/, 'Enter the external backend service URL'],
  ]
  if (translate('设置') === '设置') return text
  for (const [pattern, replacement] of replacements) {
    if (pattern.test(text)) return text.replace(pattern, replacement)
  }
  return translate(text)
}

const originalText = new WeakMap()
const originalAttributes = new WeakMap()

export function localizeDesktopDocument(document, translate, language) {
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN'
  const walker = document.createTreeWalker(
    document.body,
    globalThis.NodeFilter?.SHOW_TEXT ?? 4,
  )
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (!node.nodeValue?.trim()) continue
    if (!originalText.has(node)) originalText.set(node, node.nodeValue)
    const source = originalText.get(node)
    const leading = source.match(/^\s*/)?.[0] || ''
    const trailing = source.match(/\s*$/)?.[0] || ''
    node.nodeValue = `${leading}${translate(source.trim())}${trailing}`
  }
  for (const element of document.querySelectorAll('[title], [aria-label], [placeholder]')) {
    if (!originalAttributes.has(element)) originalAttributes.set(element, {})
    const originals = originalAttributes.get(element)
    for (const name of ['title', 'aria-label', 'placeholder']) {
      if (!element.hasAttribute(name)) continue
      originals[name] ??= element.getAttribute(name)
      element.setAttribute(name, translate(originals[name]))
    }
  }
}
