//
// 输出结构与 capSummary 的按行截断是配套设计：【参与者】【事实台账】排在前、
// 【话题脉络】排在末，所以从尾部按行舍弃正好符合信息优先级。改动段落顺序前
// 请一并检查 compaction-strategy.mjs 里的 capSummary。

